#!/usr/bin/env bash
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"
mode="${1:-test}"
case "$mode" in
  test|vet|race) ;;
  *) echo "usage: test-all-modules.sh [test|vet|race]" >&2; exit 1 ;;
esac
if [[ "$mode" == vet ]]; then
  GOWORK=off go vet ./...
  scripts/local-modfile.sh driver/blevesearch vet ./...
  GOWORK=off go -C docs vet ./...
  GOWORK=off go -C examples vet ./...
  GOWORK=off go -C integration vet -tags=integration,sqlite_fts5 ./...
else
  flags=(-count=1)
  if [[ "$mode" == race ]]; then flags+=(-race); fi
  GOWORK=off go test "${flags[@]}" ./...
  scripts/local-modfile.sh driver/blevesearch test "${flags[@]}" ./...
  GOWORK=off go -C docs test "${flags[@]}" ./...
  GOWORK=off go -C examples test "${flags[@]}" ./...
  GOWORK=off go -C integration test -tags=integration,sqlite_fts5 -run '^$' ./...
fi
